const dictionaries = {
  en,
  'zh-CN': zhCN,
  'zh-TW': zhTW,
} satisfies Record<AppLanguage, typeof zhCN>

export const languageOptions: Array<{ label: string, value: AppLanguage }> = [
  { label: 'English', value: 'en' },
  { label: '简体中文', value: 'zh-CN' },
  { label: '繁體中文', value: 'zh-TW' },
]

export type I18nKey = keyof typeof en

export function createT(language: AppLanguage) {
  const dictionary = dictionaries[language] ?? dictionaries.en
  return (key: I18nKey) => dictionary[key] ?? dictionaries.en[key]
}
